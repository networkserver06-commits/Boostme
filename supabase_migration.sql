-- The backend uses the Supabase service-role key, which bypasses RLS.
-- With no anon/authenticated policies, direct browser access is denied by default.

-- ---------- Optional helper for safe server-side wallet updates ----------
create or replace function public.apply_wallet_delta(p_user_id bigint, p_delta numeric)
returns numeric
language plpgsql
security definer
set search_path = public
as $$
declare
  v_balance numeric(14,2);
  v_next numeric(14,2);
begin
  select balance into v_balance from public.profiles where user_id = p_user_id for update;
  if not found then raise exception 'Wallet profile not found'; end if;
  v_next := round(v_balance + p_delta, 2);
  if v_next < 0 then raise exception 'Balance cannot become negative'; end if;
  update public.profiles set balance = v_next where user_id = p_user_id;
  return v_next;
end;
$$;
revoke all on function public.apply_wallet_delta(bigint, numeric) from public;

